import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
const require=createRequire(import.meta.url);
const healing=require('../docs/rts-healing.js');
const witch={x:0,z:0,health:45,maxHealth:85};
const near={id:'near',x:2,z:0,destroyed:false};
const far={id:'far',x:20,z:0,destroyed:false};
assert.ok(healing.needsRest(witch));
assert.equal(healing.nearestCircle(witch,[far,near]),near);
assert.equal(healing.nearestCircle(witch,[far,near],b=>b.id!=='near'),far);
assert.equal(healing.nearestCircle(witch,[{...near,destroyed:true}]),null);
assert.equal(healing.inside({x:2,z:0},near),true);
assert.equal(healing.inside({x:3.5,z:0},near),false);
assert.equal(healing.restore(45,85,2),67);
assert.equal(healing.restore(80,85,2),85);
assert.equal(healing.restore(84.5,85,0),84.5);
assert.throws(()=>healing.restore(45,85,-1),/Invalid healing time/);
assert.equal(healing.HEALTH_PER_MAGIC,15,'one magic point should restore fifteen HP');
const wounded={health:40,maxHealth:85};
let bill=healing.restoreGroup([wounded],1,3);
assert.equal(wounded.health,51);
assert(Math.abs(bill.spent-11/15)<1e-9);
assert(Math.abs(bill.magic-(3-11/15))<1e-9);
const empty={health:30,maxHealth:85};
bill=healing.restoreGroup([empty],3,0);
assert.equal(empty.health,30,'empty magic reserves cannot heal for free');
assert.equal(bill.spent,0);
const pair=[{health:20,maxHealth:85},{health:40,maxHealth:85}];
bill=healing.restoreGroup(pair,2,1);
assert.equal(pair[0].health,27.5);
assert.equal(pair[1].health,47.5,'two resting witches share scarce magic equally');
assert.equal(bill.magic,0);
assert(Math.abs(bill.spent-1)<1e-9);
const almostFull={health:84,maxHealth:85};
bill=healing.restoreGroup([almostFull],2,5);
assert.equal(almostFull.health,85,'never overheal');
assert(Math.abs(bill.spent-1/15)<1e-9,'charge only for actual HP restored');
bill=healing.restoreGroup([almostFull],2,bill.magic);
assert.equal(bill.spent,0,'full health costs nothing');
assert.throws(()=>healing.restoreGroup([wounded],-1,1),/Invalid healing time/);
assert.throws(()=>healing.restoreGroup([wounded],1,-1),/Invalid magic budget/);
const game=readFileSync(new URL('../docs/game.js',import.meta.url),'utf8');
assert(game.includes('matchResources.magic.witch=stoneHealing.restoreGroup(resting,dt,'),
  'the actual circle must debit the shared in-game magic reserve');
assert.equal(healing.recovered({health:80,maxHealth:85}),false);
assert.equal(healing.recovered({health:82,maxHealth:85}),true);
assert.equal(healing.needsRest({health:70,maxHealth:85}),false);
console.log('PASS standing stone circle: safe retreat, low-cost magic healing, proportional sharing, no free healing and health cap');
