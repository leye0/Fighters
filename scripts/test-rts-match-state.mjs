import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
const require=createRequire(import.meta.url);
const {create}=require('../app/rts-match-state.js');

const initialGold={witch:2000,orc:900};
const initialWood={witch:250,orc:350};
const initialMagic={witch:0,orc:0};
const state=create({gold:initialGold,wood:initialWood,magic:initialMagic});
assert(Object.isFrozen(state),'the reference owner cannot be replaced');
assert.notEqual(state.gold,initialGold);
assert.notEqual(state.wood,initialWood);
assert.notEqual(state.magic,initialMagic);
state.gold.witch-=230;
state.wood.orc+=60;
state.magic.witch+=100;state.magic.orc+=35;
assert.equal(state.gold.witch,1770);
assert.equal(state.wood.orc,410);
assert.equal(initialGold.witch,2000,'seeds are never modified');
assert.equal(initialWood.orc,350);
assert.equal(initialMagic.witch,0);
const previousMagic=state.magic;
state.resetMagic();
assert.notEqual(state.magic,previousMagic);
assert.deepEqual(state.magic,initialMagic,'spell budget resets without an economy reset');
assert.equal(state.gold.witch,1770,'resetting magic does not refund buildings');
state.magic.witch=55;
const previousGold=state.gold,previousWood=state.wood;
state.resetEconomy();
assert.notEqual(state.gold,previousGold,'new matches get fresh references');
assert.notEqual(state.wood,previousWood);
assert.deepEqual(state.gold,initialGold);
assert.deepEqual(state.wood,initialWood);
assert.equal(previousGold.witch,1770,'the previous match is left untouched');
assert.equal(state.magic.witch,55,'economy reset does not spend/reset magic early');
const getGold=()=>state.gold,getWood=()=>state.wood;
getGold().orc-=50;getWood().witch+=20;
assert.equal(state.gold.orc,850);
assert.equal(state.wood.witch,270);
state.reset();
assert.equal(getGold().orc,900,'service getters observe the new match');
assert.equal(getWood().witch,250);
assert.deepEqual(state.magic,initialMagic,'full reset clears the spell budget');

const game=readFileSync(new URL('../app/game.js',import.meta.url),'utf8');
const html=readFileSync(new URL('../app/index.html',import.meta.url),'utf8');
assert(game.includes('window.FightersMatchState.create('));
assert(game.includes('matchResources.resetMagic()'));
assert(game.includes('matchResources.resetEconomy()'));
assert(game.includes('getGold:()=>matchResources.gold,getWood:()=>matchResources.wood'));
assert(game.includes('matchResources.magic.witch=soulRules.magicAfterTime('));
assert(html.includes('src="./rts-match-state.js"'));
console.log('PASS stable match gold/wood/magic owner, reset boundaries and current economy getters');
