import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import dome from '../docs/rts-witch-dome.js';

const house={type:'witch-house',clanId:'witch',level:3,destroyed:false};
assert.equal(dome.COST,100);
assert.equal(dome.RADIUS,20);
assert.equal(dome.canCast(house,100),true);
assert.equal(dome.canCast(house,99.999),false);
assert.equal(dome.canCast({...house,level:2},100),false);
assert.equal(dome.canCast({...house,destroyed:true},100),false);
assert.equal(dome.canCast({...house,clanId:'orcs'},100),false);
assert.equal(dome.canCast({...house,type:'garden'},100),false);
assert.equal(dome.canCast(house,100,{faction:'orc'}),false);
assert.equal(dome.canCast(house,100,{paused:true}),false);
assert.equal(dome.canCast(house,100,{running:false}),false);
assert.equal(dome.canCast(house,100,{active:true}),false);
assert.equal(dome.radiusAt(0),0);
assert(dome.radiusAt(.5)>0&&dome.radiusAt(.5)<dome.RADIUS);
assert.equal(dome.radiusAt(dome.EXPAND_SECONDS),dome.RADIUS);
assert.equal(dome.radiusAt(dome.DURATION),dome.RADIUS);
assert.equal(dome.inRange({x:10,z:10},{x:30,z:10},dome.RADIUS),true);
assert.equal(dome.inRange({x:10,z:10},{x:31,z:10},dome.RADIUS),false);
assert.equal(dome.inRange({x:10,z:10},{x:10,z:10},-1),false);
const game=readFileSync(new URL('../docs/game.js',import.meta.url),'utf8');
assert(game.includes('domeRules.canCast('));
assert(game.includes('dealDamage(actor,actor.health,null)'));
assert(game.includes("effects.play('dome'"));
assert(existsSync(new URL('../docs/sounds/effects/dome/wiccans-chorus.mp3',import.meta.url)));
console.log('PASS level 3 witch dome: 100 magic, 20-unit radius, combat and audio wiring');
